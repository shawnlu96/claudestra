/**
 * 构建前生成 lib/build-info.ts —— 把当前 commit 写成**真正的源码文件**。
 *
 * 由来（2026-08-22 owner：「怎么版本号还是不同」）：原先靠 next.config.ts 在构建时
 * 用 git 现算 commit、经 DefinePlugin 注入 process.env.NEXT_PUBLIC_*。可 commit 是
 * Next 的 webpack 持久缓存**看不见**的隐藏输入：只要引用它的文件（splash.tsx）源码
 * 没变，Next 就复用缓存里的旧 chunk，把上一次的 commit 一起带出来 —— 于是每个不动
 * splash 的前端提交都让开屏页黄字复发，而这恰恰是「检测客户端滞后」这个功能自己
 * 被缓存骗了。
 *
 * 修法：把 commit 落成文件内容。文件内容随 commit 变 → webpack 缓存自然失效 →
 * 每次都烤对，且增量构建照样快（不用清缓存）。
 *
 * 非 git 环境（裸包部署）留空串，splash 只显示服务端版本，不亮黄字。
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const webDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const git = (args) => {
  try {
    return execFileSync("git", args, { cwd: webDir, encoding: "utf8" }).trim();
  } catch {
    return "";
  }
};

const commit = git(["rev-parse", "--short", "HEAD"]);
// cwd 是 web/，pathspec 用 `.` —— 与 app/api/version/route.ts 现算时同源同写法
const webCommit = git(["log", "-1", "--format=%h", "--", "."]);

const out = `// @generated by scripts/gen-build-info.mjs —— 勿手改，构建前自动重写。
// commit 落成源码文件（而非 DefinePlugin 注入），才能让 webpack 缓存随 commit 失效。
// 见该脚本头部注释（2026-08-22 版本号对不上事故）。
export const CLIENT_COMMIT = ${JSON.stringify(commit)};
export const CLIENT_WEB_COMMIT = ${JSON.stringify(webCommit)};
`;
writeFileSync(join(webDir, "lib", "build-info.ts"), out);
console.log(`[build-info] commit=${commit || "(none)"} webCommit=${webCommit || "(none)"}`);
